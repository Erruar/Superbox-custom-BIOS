#!/usr/bin/env python
"""genfont.py - bake TTF glyphs into a 1bpp C header for SbBoot.

The boot menu cannot rely on the firmware HII font (no Cyrillic on the box,
wrong look), so glyph bitmaps are baked at build time from OFL fonts:
  Space Mono      - body text, Latin
  IBM Plex Mono   - body text, Cyrillic + arrows (Space Mono lacks Cyrillic)
  Syne (wght 600) - big headings, Latin

Output: CustomSetupPkg/Application/SbBoot/fontdata.h
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FDIR = Path(r"C:\Users\Sakura\AppData\Local\Temp\opencode\fonts")

# code ranges: printable ASCII, Cyrillic, arrows
LATIN = list(range(0x20, 0x7F))
CYR = [0x401, 0x451] + list(range(0x410, 0x450))
ARROWS = [0x2191, 0x2193, 0x21B5, 0x21C5]

SET_MONO = sorted(set(LATIN + CYR + ARROWS))
SET_SYNE = sorted(set(LATIN))

# (name, font file, size, codes, variation axes or None)
SPECS = [
    ("SbMono24", "SpaceMono-Regular.ttf", 24, SET_MONO, None),
    ("SbMono19", "SpaceMono-Regular.ttf", 19, SET_MONO, None),
    ("SbSyne64", "Syne-var.ttf", 64, SET_SYNE, [600]),
    ("SbSyne34", "Syne-var.ttf", 34, SET_SYNE, [600]),
    ("SbSyne26", "Syne-var.ttf", 26, SET_SYNE, [600]),
]

PAD = 80          # canvas padding around the baseline origin
CANVAS = 400


def load_font(name, size, axes):
    f = ImageFont.truetype(str(FDIR / name), size)
    if axes:
        try:
            f.set_variation_by_axes(axes)
        except Exception:
            pass
    return f


def render(font, ch):
    """Return (w, h, adv, dx, dy, bits) for one glyph, 1bpp row-packed."""
    img = Image.new("1", (CANVAS, CANVAS), 0)
    d = ImageDraw.Draw(img)
    d.text((PAD, PAD), ch, font=font, fill=1, anchor="ls")
    box = img.getbbox()
    if box is None:
        adv = font.getlength(ch)
        return 0, 0, int(round(adv)), 0, 0, b""
    l, t, r, b = box
    w, h = r - l, b - t
    crop = img.crop(box)
    row_bytes = (w + 7) // 8
    bits = bytearray()
    for y in range(h):
        row = 0
        for x in range(w):
            if crop.getpixel((x, y)):
                row |= 0x80 >> (x & 7)
            if (x & 7) == 7:
                bits.append(row)
                row = 0
        if w & 7:
            bits.append(row)
    adv = int(round(font.getlength(ch)))
    return w, h, adv, l - PAD, t - PAD, bytes(bits)


def main():
    out = Path(sys.argv[1])
    lines = [
        "/* fontdata.h - generated by tools/genfont.py, do not edit. */",
        "#ifndef _SB_FONTDATA_H_",
        "#define _SB_FONTDATA_H_",
        "",
        "typedef struct {",
        "  UINT16  Code;",
        "  UINT8   W, H;",
        "  UINT8   Adv;            /* pen advance in pixels            */",
        "  INT8    Dx, Dy;         /* ink box offset from baseline     */",
        "  UINT16  Off;            /* byte offset into the bitmap blob */",
        "} SB_GLYPH;",
        "",
    ]
    for name, fname, size, codes, axes in SPECS:
        font = load_font(fname, size, axes)
        tab = []
        blob = bytearray()
        skipped = 0
        for c in codes:
            w, h, adv, dx, dy, bits = render(font, chr(c))
            if w == 0 and c not in (0x20,):
                skipped += 1
            off = len(blob)
            blob += bits
            tab.append((c, w, h, adv, dx, dy, off))
        lines.append(f"/* {name}: {fname} @ {size}px, {len(codes)} glyphs"
                     f" ({skipped} empty) */")
        lines.append(f"STATIC CONST SB_GLYPH {name}_Tab[] = {{")
        for c, w, h, adv, dx, dy, off in tab:
            lines.append(f"  {{ 0x{c:04X}, {w}, {h}, {adv}, {dx}, {dy}, {off} }},")
        lines.append("};")
        lines.append(f"STATIC CONST UINT8 {name}_Bits[] = {{")
        # 16 bytes per row
        s = ",".join(str(b) for b in blob)
        for i in range(0, len(s), 96):
            chunk = s[i:i + 96]
            lines.append("  " + chunk + ("," if i + 96 < len(s) else ""))
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"[genfont] wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
