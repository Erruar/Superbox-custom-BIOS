#!/usr/bin/env python
"""genfont.py - bake TTF glyphs into a 1bpp C header for SbBoot.

The boot menu cannot rely on the firmware HII font (no Cyrillic on the box,
wrong look), so glyph bitmaps are baked at build time from OFL fonts:
  Space Mono      - body text, Latin
  IBM Plex Mono   - body text, Cyrillic + arrows (Space Mono lacks Cyrillic)
  Syne (wght 600) - big headings, Latin

Output: CustomSetupPkg/Application/SbBoot/fontdata.h
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FDIR = Path(__file__).resolve().parent.parent / "fonts"

GF = "https://github.com/google/fonts/raw/main/ofl/"
FONT_SOURCES = {
    "SpaceMono-Regular.ttf":   GF + "spacemono/SpaceMono-Regular.ttf",
    "IBMPlexMono-Regular.ttf": GF + "ibmplexmono/IBMPlexMono-Regular.ttf",
    "Syne-var.ttf":            GF + "syne/Syne%5Bwght%5D.ttf",
    # DejaVu (Bitstream Vera license, permissive) ships with matplotlib
    "DejaVuSansMono.ttf":      (r"C:\Users\Sakura\AppData\Local\Programs\Python"
                                r"\Python312\Lib\site-packages\matplotlib"
                                r"\mpl-data\fonts\ttf\DejaVuSansMono.ttf"),
}


def ensure_fonts():
    import shutil
    import urllib.request
    FDIR.mkdir(parents=True, exist_ok=True)
    for name, src in FONT_SOURCES.items():
        dst = FDIR / name
        if dst.exists():
            continue
        if src.startswith("http"):
            urllib.request.urlretrieve(src, dst)
        else:
            shutil.copyfile(src, dst)
        print("[genfont] fetched", name)

# code ranges: printable ASCII, Cyrillic, arrows
LATIN = list(range(0x20, 0x7F))
CYR = [0x401, 0x451] + list(range(0x410, 0x450))
ARROWS = [0x2191, 0x2193, 0x21B5, 0x21C5]

ALL = sorted(set(LATIN + CYR + ARROWS))
SET_SYNE = sorted(set(LATIN))

# (name, [(font file, size, codes, variation axes or None), ...]) - earlier
# entries win; later fonts fill the glyphs the primary one lacks (Cyrillic,
# arrows).  Glyphs a font renders as .notdef "tofu" are detected and skipped.
SPECS = [
    ("SbMono24", [("SpaceMono-Regular.ttf", 24, ALL, None),
                  ("IBMPlexMono-Regular.ttf", 24, ALL, None),
                  ("DejaVuSansMono.ttf", 24, ALL, None)]),
    ("SbMono19", [("SpaceMono-Regular.ttf", 19, ALL, None),
                  ("IBMPlexMono-Regular.ttf", 19, ALL, None),
                  ("DejaVuSansMono.ttf", 19, ALL, None)]),
    ("SbSyne64", [("Syne-var.ttf", 64, SET_SYNE, [600])]),
    ("SbSyne34", [("Syne-var.ttf", 34, SET_SYNE, [600]),
                  ("DejaVuSansMono.ttf", 34, ARROWS, None)]),
    ("SbSyne26", [("Syne-var.ttf", 26, SET_SYNE, [600])]),
]

PAD = 80          # canvas padding around the baseline origin
CANVAS = 400


def load_font(name, size, axes):
    f = ImageFont.truetype(str(FDIR / name), size)
    if axes:
        try:
            f.set_variation_by_axes(axes)
        except Exception:
            pass
    return f


def render(font, ch):
    """Return (w, h, adv, dx, dy, bits) for one glyph, 1bpp row-packed."""
    img = Image.new("1", (CANVAS, CANVAS), 0)
    d = ImageDraw.Draw(img)
    d.text((PAD, PAD), ch, font=font, fill=1, anchor="ls")
    box = img.getbbox()
    if box is None:
        adv = font.getlength(ch)
        return 0, 0, int(round(adv)), 0, 0, b""
    l, t, r, b = box
    w, h = r - l, b - t
    crop = img.crop(box)
    row_bytes = (w + 7) // 8
    bits = bytearray()
    for y in range(h):
        row = 0
        for x in range(w):
            if crop.getpixel((x, y)):
                row |= 0x80 >> (x & 7)
            if (x & 7) == 7:
                bits.append(row)
                row = 0
        if w & 7:
            bits.append(row)
    adv = int(round(font.getlength(ch)))
    return w, h, adv, l - PAD, t - PAD, bytes(bits)


def main():
    ensure_fonts()
    out = Path(sys.argv[1])
    lines = [
        "/* fontdata.h - generated by tools/genfont.py, do not edit. */",
        "#ifndef _SB_FONTDATA_H_",
        "#define _SB_FONTDATA_H_",
        "",
        "typedef struct {",
        "  UINT16  Code;",
        "  UINT8   W, H;",
        "  UINT8   Adv;            /* pen advance in pixels            */",
        "  INT8    Dx, Dy;         /* ink box offset from baseline     */",
        "  UINT16  Off;            /* byte offset into the bitmap blob */",
        "} SB_GLYPH;",
        "",
    ]
    for name, fonts in SPECS:
        loaded = []
        for f, size, codes, axes in fonts:
            font = load_font(f, size, axes)
            tofu = render(font, "￿")  # FFFF: maps to .notdef in every font
            loaded.append((font, size, set(codes), tofu))
        tab = []
        blob = bytearray()
        skipped = 0
        codes = sorted(set().union(*[s for _, _, s, _ in loaded]))
        for c in codes:
            chosen = None
            for font, _size, cset, tofu in loaded:
                if c not in cset:
                    continue
                g = render(font, chr(c))
                w, h, adv, dx, dy, bits = g
                if w == 0:
                    continue
                if (w, h, bits) == (tofu[0], tofu[1], tofu[5]):
                    continue          # .notdef tofu - try the next font
                chosen = g
                break
            if chosen is None:
                skipped += 1
                w, h, adv, dx, dy, bits = 0, 0, int(round(
                    loaded[0][0].getlength(chr(c)))), 0, 0, b""
            else:
                w, h, adv, dx, dy, bits = chosen
            off = len(blob)
            blob += bits
            tab.append((c, w, h, adv, dx, dy, off))
        src = " + ".join(f"{f} @ {s}" for f, s, _, _ in fonts)
        lines.append(f"/* {name}: {src}, {len(codes)} glyphs ({skipped} empty) */")
        lines.append(f"STATIC CONST SB_GLYPH {name}_Tab[] = {{")
        for c, w, h, adv, dx, dy, off in tab:
            lines.append(f"  {{ 0x{c:04X}, {w}, {h}, {adv}, {dx}, {dy}, {off} }},")
        lines.append("};")
        lines.append(f"STATIC CONST UINT8 {name}_Bits[] = {{")
        # 16 bytes per row
        vals = [str(b) for b in blob]
        for i in range(0, len(vals), 16):
            chunk = vals[i:i + 16]
            lines.append("  " + ",".join(chunk) +
                         ("," if i + 16 < len(vals) else ""))
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"[genfont] wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
